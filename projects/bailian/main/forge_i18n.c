const char *forge_tr(game_handle_t g,const char *text)
{
    if(!text||!g||g->language!=GAME_LANGUAGE_EN)return text;
    if(!text[0]||((unsigned char)text[0]<128&&!text[1]))return text;
    size_t low=0,high=sizeof(translations)/sizeof(translations[0]);
    while(low<high){
        size_t mid=low+(high-low)/2;
        int compare=strcmp(text,translations[mid].zh);
        if(compare==0)return translations[mid].en;
        if(compare<0)high=mid;else low=mid+1;
    }
    return text;
}
bool game_set_language(game_handle_t g,game_language_t language)
{
    if(!g||language<0||language>=GAME_LANGUAGE_COUNT)return false;
    if(g->language!=(uint8_t)language){
        g->language=(uint8_t)language;
        /* Discard an already formatted toast from the previous language. */
        g->notice_ms=0;g->notice[0]=0;
    }
    return true;
}
game_language_t game_get_language(game_handle_t g)
{
    return g?(game_language_t)g->language:GAME_LANGUAGE_ZH;
}
